export const PORTFOLIO_ITEMS = ALL_PORTFOLIO_ITEMS.filter((item) => !item.hidden);

export function getPortfolioBySlug(slug) {
  if (!slug) return null;
  return PORTFOLIO_ITEMS.find((item) => item.slug === slug) ?? null;
}

export function getHomePortfolioPreview() {
  return PORTFOLIO_ITEMS.filter((item) => item.homePreview).slice(0, 3);
}

export function getPortfolioDetailRoutes() {
  return PORTFOLIO_ITEMS.filter((item) => item.slug && item.detail).map((item) => ({
    path: `/portfolio/${item.slug}`,
    folder: `portfolio/${item.slug}`,
    title: item.detail.title,
    description: item.detail.description,
    changefreq: "monthly",
    priority: "0.7"
  }));
}

export function filterPortfolioItems(kind = "all") {
  if (!kind || kind === "all") return PORTFOLIO_ITEMS;
  return PORTFOLIO_ITEMS.filter((item) => item.kind === kind || (item.placeholder && kind === "site"));
}
